type CaseRow = Database['public']['Tables']['cases']['Row'];

export interface FileCaseResult {
  ok: boolean;
  /** `public_id` of the new case, e.g. "CASE-7501". Used to redirect. */
  publicId?: string;
  error?: string;
  fieldErrors?: Record<string, string>;
}

/**
 * Files a new case.
 *
 * Pipeline order is deliberate and must not be reordered:
 *   auth/tier → rate limit → Zod → redact (reject hard PII) → profanity →
 *   sanitize → insert
 *
 * Redaction runs before anything is persisted or sent to an LLM, so raw contact
 * details never leave this function.
 */
export async function fileCase(formData: FormData): Promise<FileCaseResult> {
  const viewer = await getViewer();

  // Gate 1 of 3 on the verified-only rule. RLS and `can_file_case()` are the
  // others — this one exists to produce a useful message.
  if (!viewer.canFile) {
    return {
      ok: false,
      error: viewer.fileBlockedReason
        ? FILE_BLOCKED_MESSAGES[viewer.fileBlockedReason]
        : 'You cannot file a case right now.',
    };
  }

  const ip = clientIp(await headers());
  const limit = await checkLimit('case:create', `${viewer.userId}:${ip}`);
  if (!limit.ok) return { ok: false, error: limitMessage(limit) };

  const parsed = fileCaseSchema.safeParse({
    category: formData.get('category'),
    title: formData.get('title'),
    body: formData.get('body'),
    persona: formData.get('persona') ?? DEFAULT_PERSONA,
    acceptedRules: formData.get('acceptedRules') === 'on',
  });
  if (!parsed.success) {
    return { ok: false, fieldErrors: fieldErrors(parsed.error) };
  }

  const { category, title, body, persona } = parsed.data;

  // Hard PII check across both fields. Rejecting beats silently redacting: the
  // author learns the rule instead of assuming it posted fine.
  const titleCheck = redact(title);
  const bodyCheck = redact(body);
  const rejections = [
    ...new Set([...titleCheck.rejections, ...bodyCheck.rejections]),
  ];
  if (rejections.length > 0) {
    return { ok: false, fieldErrors: { body: rejectionMessage(rejections) } };
  }

  const profanity = scanProfanity(`${title}\n${body}`);
  if (profanity.hasSevere) {
    return { ok: false, fieldErrors: { body: SEVERE_MESSAGE } };
  }

  const cleanTitle = sanitizeText(titleCheck.text);
  const cleanBody = sanitizeText(bodyCheck.text);

  // Sanitizing can shorten text; re-check the floor so an empty case can't slip in.
  if (cleanTitle.length < 8 || cleanBody.length < 60) {
    return {
      ok: false,
      fieldErrors: {
        body: 'That did not survive cleanup. Rewrite it as plain text.',
      },
    };
  }

  /*
   * Insert with the service client.
   *
   * `public_id` is generated by a DB default (a sequence), and `status` must be
   * set to 'live' — but `status` is a privileged column that the guard trigger
   * blocks for non-service roles. Authorisation has already been established
   * above via `viewer.canFile`, and `author_id` is taken from the verified
   * session rather than the form.
   *
   * A profanity hit does not block; it routes the case to `pending_review` so a
   * human sees it before the public does.
   */
  const admin = createServiceClient();
  const initialStatus: CaseStatus =
    profanity.hasProfanity || viewer.isShadowBanned ? 'pending_review' : 'live';

  /*
   * `public_id` is omitted deliberately: the DB default calls
   * `next_public_case_id()`, which removes any client-side race over case numbers.
   */
  const { data, error } = await admin
    .from('cases')
    .insert({
      author_id: viewer.userId!,
      category,
      title: cleanTitle,
      body: cleanBody,
      judge_persona: persona,
      status: initialStatus,
      language: 'en',
    })
    .select('public_id')
    .single();

  if (error) {
    console.error('[cases] insert failed:', error.message);
    return { ok: false, error: 'Could not file the case. Try again.' };
  }

  revalidatePath('/');
  return { ok: true, publicId: data.public_id };
}

